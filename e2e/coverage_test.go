var updateCoverage = flag.Bool("update-coverage", false,
	"rewrite the generated part of COVERAGE.md from the goldens")

const (
	coverageFile  = "COVERAGE.md"
	matrixBegin   = "<!-- coverage:begin (generated by go test ./e2e -run TestCoverage -update-coverage) -->"
	matrixEnd     = "<!-- coverage:end -->"
	goldenRoot    = "testdata/golden"
	exitStatusTag = "exit status: "
)

// TestCoverage is the coverage guard: it runs with go test ./... (no container)
// and fails when a supported Harness has no image, when a step lacks its golden,
// when a (scenario, Harness) cell has neither a golden proving the claimed
// result nor a justified exclusion, or when COVERAGE.md is stale.
func TestCoverage(t *testing.T) {
	if _, err := os.Stat("Dockerfile"); err != nil {
		t.Skip("the coverage guard runs from the e2e source directory (go test ./e2e)")
	}
	harnesses := harnessIDs()
	t.Run("harness-images", func(t *testing.T) { checkHarnessImages(t, harnesses) })
	t.Run("steps", func(t *testing.T) { checkSteps(t, harnesses) })
	rows := make([][]string, len(scenarios))
	seen := map[string]bool{}
	for i, sc := range scenarios {
		if seen[sc.id] {
			t.Errorf("duplicate scenario id %s", sc.id)
		}
		seen[sc.id] = true
		rows[i] = make([]string, len(harnesses))
		for j, h := range harnesses {
			cell, err := evaluateCell(sc, h)
			if err != nil {
				t.Errorf("%s × %s: %v", sc.id, h, err)
			}
			rows[i][j] = cell
		}
	}
	t.Run("matrix", func(t *testing.T) { checkMatrix(t, harnesses, rows) })
}

// checkHarnessImages requires an e2e image, a run.sh entry and a CI job for
// every supported Harness.
func checkHarnessImages(t *testing.T, harnesses []string) {
	dockerfile := readText(t, "Dockerfile")
	runSh := readText(t, "run.sh")
	workflow := readText(t, filepath.Join("..", ".github", "workflows", "e2e.yml"))
	for _, h := range harnesses {
		if !strings.Contains(dockerfile, "FROM harness-"+h+" AS e2e-"+h+"\n") {
			t.Errorf("e2e/Dockerfile has no e2e-%s target", h)
		}
		if !strings.Contains(runSh, " "+h+" ") && !strings.Contains(runSh, "("+h+" ") &&
			!strings.Contains(runSh, " "+h+")") {
			t.Errorf("e2e/run.sh does not list %s", h)
		}
		if !strings.Contains(workflow, "harness: "+h+",") {
			t.Errorf(".github/workflows/e2e.yml has no job for %s", h)
		}
		if _, ok := liveCredentials[h]; !ok {
			t.Errorf("liveCredentials has no entry for %s", h)
		}
	}
}

// checkSteps requires a golden for every step each Harness runs, no golden for
// a step it does not run, and a scenario for every step.
func checkSteps(t *testing.T, harnesses []string) {
	referenced := map[string]bool{}
	for _, sc := range scenarios {
		for _, e := range scenarioEvidence(sc) {
			for _, step := range e.allSteps() {
				referenced[step] = true
				if _, ok := stepSpecs[step]; !ok {
					t.Errorf("scenario %s refers to unknown step %s", sc.id, step)
				}
			}
		}
	}
	for step := range stepSpecs {
		if !referenced[step] {
			t.Errorf("step %s proves no scenario; add it to a scenario in coverage.go", step)
		}
	}
	for _, h := range harnesses {
		dirs, err := os.ReadDir(filepath.Join(goldenRoot, h))
		if err != nil {
			t.Errorf("no goldens for %s: %v (run make e2e-update HARNESS=%s)", h, err, h)
			continue
		}
		have := map[string]bool{}
		for _, d := range dirs {
			have[d.Name()] = true
			spec, ok := stepSpecs[d.Name()]
			if !ok || !spec.appliesTo(h) {
				t.Errorf("stale golden %s/%s: no step produces it", h, d.Name())
			}
		}
		for step, spec := range stepSpecs {
			if spec.appliesTo(h) && !have[step] {
				t.Errorf("%s runs %s but has no golden (run make e2e-update HARNESS=%s)",
					h, step, h)
			}
		}
	}
}

func scenarioEvidence(sc scenario) []evidence {
	out := []evidence{sc.all}
	for _, e := range sc.per {
		out = append(out, e)
	}
	return out
}

func (e evidence) allSteps() []string {
	var steps []string
	if e.plan != "" {
		steps = append(steps, e.plan)
	}
	steps = append(steps, e.install...)
	if e.refuse != "" {
		steps = append(steps, e.refuse)
	}
	steps = append(steps, e.absent...)
	return append(steps, e.steps...)
}

// golden is what TestCoverage reads from one step's golden directory.
type golden struct {
	exit  int
	items []goldenItem
	files string
}

type goldenItem struct {
	Agent   string `json:"agent"`
	Harness string `json:"harness"`
	Action  string `json:"action"`
}

func readGolden(harness, step string) (*golden, error) {
	dir := filepath.Join(goldenRoot, harness, step)
	run, err := os.ReadFile(filepath.Join(dir, "run.txt"))
	if err != nil {
		return nil, fmt.Errorf("no golden for step %s: %w", step, err)
	}
	g := &golden{exit: -1}
	for _, line := range strings.Split(string(run), "\n") {
		if rest, ok := strings.CutPrefix(line, exitStatusTag); ok {
			g.exit, err = strconv.Atoi(rest)
			if err != nil {
				return nil, fmt.Errorf("%s/run.txt: %w", dir, err)
			}
		}
	}
	if g.exit < 0 {
		return nil, fmt.Errorf("%s/run.txt records no exit status", dir)
	}
	files, err := os.ReadFile(filepath.Join(dir, "files.txt"))
	if err != nil {
		return nil, err
	}
	g.files = string(files)
	stdout, err := os.ReadFile(filepath.Join(dir, "stdout.json"))
	switch {
	case os.IsNotExist(err):
	case err != nil:
		return nil, err
	case bytes.HasPrefix(bytes.TrimSpace(stdout), []byte("{")):
		var plan struct {
			Items []goldenItem `json:"items"`
		}
		if err := sonic.Unmarshal(stdout, &plan); err != nil {
			return nil, fmt.Errorf("%s/stdout.json: %w", dir, err)
		}
		g.items = plan.Items
	}
	return g, nil
}

// outcome is the agent's result for harness in g: "W" when every item writes,
// "R" when any is refused, "" when g has no item for it.
func (g *golden) outcome(agentID, harness string) string {
	result := ""
	for _, item := range g.items {
		if item.Agent != agentID || item.Harness != harness {
			continue
		}
		switch item.Action {
		case "create", "replace", "unchanged":
			if result == "" {
				result = "W"
			}
		default:
			result = "R"
		}
	}
	return result
}

// nativeMark is the native proof of step for harness: "N" (the real Harness
// loaded what it installed), "N0" (it provably does not load that scope, see
// nativeExclusions) or "".
func nativeMark(step, harness string) string {
	spec := stepSpecs[step]
	if !spec.native {
		return ""
	}
	if _, excluded := nativeExclusions[harness][spec.scope]; excluded {
		return "N0"
	}
	return "N"
}

// evaluateCell checks the evidence of sc for harness against the goldens and
// returns the matrix cell.
func evaluateCell(sc scenario, harness string) (string, error) {
	if reason, ok := sc.excluded[harness]; ok {
		if strings.TrimSpace(reason) == "" {
			return "", fmt.Errorf("exclusion without a reason")
		}
		return "excluded", nil
	}
	e := sc.all
	if per, ok := sc.per[harness]; ok {
		e = per
	}
	for _, step := range e.allSteps() {
		if !stepSpecs[step].appliesTo(harness) {
			return "", fmt.Errorf("step %s does not run for %s", step, harness)
		}
	}
	marks := map[string]bool{}
	if sc.agent != "" {
		if err := agentCell(sc, e, harness, marks); err != nil {
			return "", err
		}
	}
	if err := stepsCell(e, harness, marks); err != nil {
		return "", err
	}
	if len(marks) == 0 {
		return "", fmt.Errorf("no evidence")
	}
	return formatMarks(marks), nil
}

func agentCell(sc scenario, e evidence, harness string, marks map[string]bool) error {
	for _, step := range e.absent {
		g, err := readGolden(harness, step)
		if err != nil {
			return err
		}
		if g.exit != 0 || g.outcome(sc.agent, harness) != "" {
			return fmt.Errorf("the %s golden must succeed without %s", step, sc.agent)
		}
		marks["A"] = true
	}
	if e.plan == "" && len(e.install) == 0 {
		return nil
	}
	installable := true
	if e.plan != "" {
		g, err := readGolden(harness, e.plan)
		if err != nil {
			return err
		}
		switch g.outcome(sc.agent, harness) {
		case "":
			return fmt.Errorf("the %s golden does not list %s", e.plan, sc.agent)
		case "R":
			installable = false
		}
	}
	if !installable {
		marks["R"] = true
		if e.refuse == "" {
			return nil
		}
		g, err := readGolden(harness, e.refuse)
		if err != nil {
			return err
		}
		if g.outcome(sc.agent, harness) != "R" || g.exit == 0 {
			return fmt.Errorf("%s is refused in %s but not in the %s golden",
				sc.agent, e.plan, e.refuse)
		}
		return nil
	}
	if len(e.install) == 0 {
		marks["W"] = true // installable in the plan; the plan writes nothing
		return nil
	}
	for _, step := range e.install {
		g, err := readGolden(harness, step)
		if err != nil {
			return err
		}
		if g.outcome(sc.agent, harness) != "W" || g.exit != 0 {
			return fmt.Errorf("%s is installable but the %s golden does not write it",
				sc.agent, step)
		}
		marks["W"] = true
		if mark := nativeMark(step, harness); mark != "" {
			marks[mark] = true
		}
	}
	return nil
}

func stepsCell(e evidence, harness string, marks map[string]bool) error {
	for _, step := range e.steps {
		g, err := readGolden(harness, step)
		if err != nil {
			return err
		}
		if g.exit != 0 {
			marks["R"] = true
			continue
		}
		marks["✓"] = true
		if e.contains != "" && !strings.Contains(g.files, e.contains) {
			return fmt.Errorf("the %s golden wrote no %s", step, e.contains)
		}
		if mark := nativeMark(step, harness); mark != "" {
			marks[mark] = true
		}
	}
	return nil
}

var markOrder = []string{"W", "✓", "R", "A", "N", "N0"}

func formatMarks(marks map[string]bool) string {
	var parts []string
	for _, m := range markOrder {
		if marks[m] {
			parts = append(parts, m)
		}
	}
	return strings.Join(parts, " ")
}

// scopeSources summarizes the scopes and source kinds of the steps proving sc.
func scopeSources(sc scenario) string {
	set := map[string]bool{}
	for _, e := range scenarioEvidence(sc) {
		for _, step := range e.allSteps() {
			spec := stepSpecs[step]
			scope := map[string]string{
				scopeProj: "project", scopeUser: "global", scopeNone: "inventory",
			}[spec.scope]
			set[scope+" · "+spec.source] = true
		}
	}
	list := make([]string, 0, len(set))
	for k := range set {
		list = append(list, k)
	}
	sort.Strings(list)
	return strings.Join(list, "<br>")
}

func renderMatrix(harnesses []string, rows [][]string) string {
	var b strings.Builder
	b.WriteString(matrixBegin + "\n")
	group := ""
	header := "| Scenario | Fixture agent | Scope · source | " + strings.Join(harnesses, " | ") +
		" |\n|---|---|---|" + strings.Repeat("---|", len(harnesses)) + "\n"
	for i, sc := range scenarios {
		if sc.group != group {
			group = sc.group
			fmt.Fprintf(&b, "\n### %s\n\n%s", group, header)
		}
		agentCol := "—"
		if sc.agent != "" {
			agentCol = "`" + sc.agent + "`"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n",
			sc.title, agentCol, scopeSources(sc), strings.Join(rows[i], " | "))
	}
	b.WriteString("\n### Exclusions\n\n")
	var exclusions []string
	for _, sc := range scenarios {
		for h, reason := range sc.excluded {
			exclusions = append(exclusions, fmt.Sprintf("- %s × %s: %s", sc.id, h, reason))
		}
	}
	for h, scopes := range nativeExclusions {
		for scope, reason := range scopes {
			exclusions = append(exclusions,
				fmt.Sprintf("- native check, %s × %s scope (`N0`): %s", h, scope, reason))
		}
	}
	slices.Sort(exclusions)
	if len(exclusions) == 0 {
		exclusions = []string{"None."}
	}
	b.WriteString(strings.Join(exclusions, "\n") + "\n")
	b.WriteString(
		"\n### Live tier\n\n| Harness | Secret (first set wins) | How the installed agent " +
			"is run |\n|---|---|---|\n",
	)
	for _, h := range harnesses {
		live := liveCredentials[h]
		fmt.Fprintf(&b, "| %s | `%s` | %s |\n", h, strings.Join(live.secrets, "`, `"), live.how)
	}
	b.WriteString(matrixEnd)
	return b.String()
}

func checkMatrix(t *testing.T, harnesses []string, rows [][]string) {
	content := readText(t, coverageFile)
	start := strings.Index(content, matrixBegin)
	end := strings.Index(content, matrixEnd)
	if start < 0 || end < start {
		t.Fatalf("%s has no generated coverage section", coverageFile)
	}
	want := renderMatrix(harnesses, rows)
	got := content[start : end+len(matrixEnd)]
	if got == want {
		return
	}
	if *updateCoverage {
		updated := content[:start] + want + content[end+len(matrixEnd):]
		if err := os.WriteFile(coverageFile, []byte(updated), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Errorf(
		"%s is stale; run go test ./e2e -run TestCoverage -update-coverage and review the diff",
		coverageFile,
	)
}

func readText(t *testing.T, path string) string {
	t.Helper()
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(content)
}
